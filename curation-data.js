window.isFranchise = function(name) {
  if (!name) return false;
  const norm = String(name).toLowerCase().replace(/\s+/g, '');
  for (const kw of (window.CURATION_FRANCHISE_BLACKLIST || [])) {
    const k = String(kw).toLowerCase().replace(/\s+/g, '');
    if (k && norm.includes(k)) return true;
  }
  return false;
};

