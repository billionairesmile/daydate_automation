// ============================================================
// 데이터 정상화 (sanitize) — localStorage에 누적된 legacy 데이터 정리
// ============================================================
//
// 다양한 import 경로(applyTopByCity, applyDiningcodePool, kakao 키워드 검색 등)에서
// 들어온 record들의 cuisine/district 필드가 어색한 상태가 되어있는 경우를 정리한다.
//
// - cuisine = "명동" / "강남" / 빈값 / 카테고리 영어명 등 → 메뉴/이름으로 재분류
// - district = "대전 카페" / "서울한식" / 광역시명 그 자체 / 카테고리 키워드 → null
// - category="cafe"이면 cuisine="카페" 강제
//
// 정상화는 idempotent: 이미 정상인 값에는 영향 없음.
// ============================================================
const _CURATION_VALID_CUISINES = new Set(window.CURATION_CUISINES_PRIMARY);
const _CURATION_VALID_REGIONS = new Set(window.CURATION_REGIONS);
const _DISTRICT_GARBAGE_KEYWORDS = /(카페|디저트|술집|식당|음식점|맛집|베이커리|커피|brunch|cafe|coffee)/i;

function _curationSanitizePlace(p) {
  if (!p || typeof p !== 'object') return p;

  // 2026-05-25: park / spot / museum / theme_park / prop_shop / photo_spot / landmark 은 cuisine 분류 체계 없음 → 정상화 스킵
  // 2026-06-04: bar(술집)는 자체 4분류(주점/이자카야/펍·맥주/와인·칵테일바)를 DB가 source-of-truth 로 가짐.
  //   _classifyCuisine(식당 9분류)은 이를 모르므로(예: 이자카야→일식 오분류) 정상화 스킵하고 DB cuisine 보존.
  if (p.category === 'park' || p.category === 'spot' || p.category === 'museum'
      || p.category === 'theme_park' || p.category === 'prop_shop'
      || p.category === 'photo_spot' || p.category === 'landmark'
      || p.category === 'bar') {
    return p;
  }

  // 1) cuisine 정상화
  let cuisine = p.cuisine;
  if (p.category === 'cafe') {
    // 카페 카테고리는 cuisine 무조건 "카페"
    cuisine = '카페';
  } else if (p.category === 'restaurant' && typeof cuisine === 'string' && _CURATION_VALID_CUISINES.has(cuisine)) {
    // 2026-06-01: 식당은 Supabase(dc-restaurant-bot)가 cuisine source-of-truth — 신뢰하고 그대로 유지.
    //   _classifyCuisine은 9분류(고기/해산물/아시안/브런치)를 모르므로 덮어쓰면 잘못된 한식으로 회귀함.
  } else if (typeof cuisine !== 'string' || !_CURATION_VALID_CUISINES.has(cuisine)) {
    // 비정상이면 메뉴/이름으로 재분류
    cuisine = _classifyCuisine(p.menu, p.name);
  } else if (!p._modified) {
    // valid이지만 user override가 아닌 자동 수집/legacy 데이터는 항상 fresh classifier로 재평가.
    //   - 멕시칼리 같은 매장이 옛 classifier 시절 default 한식으로 저장된 케이스를 잡기 위함.
    //   - classifier가 default(한식)가 아닌 명시 분류(양식/일식/중식/카페/분식/술집)를
    //     산출하고 현재값과 다르면 새 결과를 채택.
    //   - classifier 결과가 한식이면 현재값 유지(과교정 방지).
    const reclassified = _classifyCuisine(p.menu, p.name);
    if (reclassified !== '한식' && reclassified !== cuisine) {
      cuisine = reclassified;
    }
  }
  // user-modified (override 적용된) record는 위 분기에 진입하지 않으므로 사용자 입력 보존.

  // 2) district 정상화
  let district = p.district;
  if (district != null) {
    const d = String(district).trim();

    // 빈값 → null
    if (!d) {
      district = null;
    } else if (_CURATION_VALID_REGIONS.has(d)) {
      // 광역시도명 그 자체 → 광역 본체이므로 district는 null
      district = null;
    } else if (_CURATION_VALID_CUISINES.has(d)) {
      // cuisine 키워드가 district에 들어가있음 → null
      district = null;
    } else if (_DISTRICT_GARBAGE_KEYWORDS.test(d)) {
      // "대전 카페", "서울 한식" 등 카테고리성 문자열 → null
      district = null;
    } else {
      // region 이름이 prefix로 들어간 경우 ("대전 + 무언가") 분리 시도
      let cleaned = d;
      for (const r of _CURATION_VALID_REGIONS) {
        if (cleaned.startsWith(r)) {
          const rest = cleaned.slice(r.length).trim();
          if (!rest || _CURATION_VALID_CUISINES.has(rest) || _DISTRICT_GARBAGE_KEYWORDS.test(rest)) {
            cleaned = '';
          } else {
            cleaned = rest;
          }
          break;
        }
      }
      district = cleaned || null;
    }
  }

  // 3) 광역시 본체(city===region이고 둘 다 광역시)면 district는 null
  if (district && p.region && p.city === p.region && _CURATION_VALID_REGIONS.has(p.region)) {
    district = null;
  }

  // 변경된 경우에만 새 객체 반환 (불필요한 alloc 방지)
  if (cuisine === p.cuisine && district === p.district) return p;
  return { ...p, cuisine, district };
}

window._curationSanitizePlace = _curationSanitizePlace;
window._curationSanitizePlaces = function(arr) {
  if (!Array.isArray(arr)) return arr;
  return arr.map(_curationSanitizePlace);
};
